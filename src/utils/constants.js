    // Helper: Strict Priority-Based Substring Matching for Contextual Career Roles
    export const getRecommendedRoles = (degree) => {
      const lowerDegree = degree?.toLowerCase() || "";

      // PRIORITY 1: Commerce & Business (Catches B.Com even if it has "Statistics" or "Analytics" in the name)
      if (
        lowerDegree.includes("b.com") || 
        lowerDegree.includes("commerce") || 
        lowerDegree.includes("bba") || 
        lowerDegree.includes("mba") ||
        lowerDegree.includes("finance") ||
        lowerDegree.includes("accounting") ||
        lowerDegree.includes("banking")
      ) {
        return DEGREE_ROLE_RECOMMENDATIONS.commerce;
      }

      // PRIORITY 2: Tech & Engineering
      if (
        lowerDegree.includes("b.tech") || 
        lowerDegree.includes("b.e") || 
        lowerDegree.includes("bca") || 
        lowerDegree.includes("mca") ||
        lowerDegree.includes("computer") || 
        lowerDegree.includes("software") || 
        lowerDegree.includes("it") ||
        lowerDegree.includes("information technology")
      ) {
        return DEGREE_ROLE_RECOMMENDATIONS.engineering;
      }

      // PRIORITY 3: Pure Science / Math / Stats (Will only hit if B.Com/B.Tech wasn't found)
      if (
        lowerDegree.includes("b.sc") || 
        lowerDegree.includes("statistics") || 
        lowerDegree.includes("mathematics") ||
        lowerDegree.includes("data analytics") ||
        lowerDegree.includes("data science") ||
        lowerDegree.includes("quantitative") ||
        lowerDegree.includes("actuarial")
      ) {
        return DEGREE_ROLE_RECOMMENDATIONS.statistics;
      }

      // PRIORITY 4: Generic Fallback
      return DEGREE_ROLE_RECOMMENDATIONS.default;
    };

